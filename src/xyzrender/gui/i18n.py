def set_lang(lang: str) -> None:
    global _CURRENT_LANG
    if lang in LANGUAGES:
        _CURRENT_LANG = lang


def get_lang() -> str:
    return _CURRENT_LANG


def _(text: str) -> str:
    """Translate *text* to the current language, or return it unchanged."""
    if _CURRENT_LANG == "en":
        return text
    return _TRANSLATIONS.get(text, text)
